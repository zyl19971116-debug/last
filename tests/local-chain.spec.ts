import {expect,test} from '@playwright/test';

test('real Anvil countdown lifecycle',async({page,request})=>{
 const initialResponse=await request.get('/api/dev/anvil');
 expect(initialResponse.ok()).toBeTruthy();
 const initial=await initialResponse.json();
 expect(initial.chainId).toBe(31337);
 expect(initial.epoch.endTime-initial.epoch.startTime).toBe(604800);
 await page.goto('/');
 await expect(page.getByText('LOCAL TESTNET')).toBeVisible();
 await expect(page.locator('.core-status strong')).toHaveText(`#${String(initial.epoch.id).padStart(3,'0')}`);
 const seconds=page.locator('.core .countdown strong').last();
 const beforeTick=await seconds.textContent();
 await page.waitForTimeout(1100);
 expect(await seconds.textContent()).not.toBe(beforeTick);
 const firstResponse=await request.post('/api/dev/anvil',{data:{action:'sendSignal'}});
 expect(firstResponse.ok()).toBeTruthy();
 const first=await firstResponse.json();
 expect(first.transaction.status).toBe('success');
 expect(first.epoch.endTime-initial.epoch.endTime).toBe(3600);
 expect(first.epoch.totalSignals-initial.epoch.totalSignals).toBe(1);
 const duplicate=await request.post('/api/dev/anvil',{data:{action:'sendSignal'}});
 expect(duplicate.status()).toBe(400);
 expect((await duplicate.json()).error).toContain('ALREADY SENT TODAY');
 const advanced=await (await request.post('/api/dev/anvil',{data:{action:'advanceDay'}})).json();
 expect(advanced.eligibility.canSignal).toBe(true);
 const second=await (await request.post('/api/dev/anvil',{data:{action:'sendSignal'}})).json();
 expect(second.transaction.status).toBe('success');
 const ended=await (await request.post('/api/dev/anvil',{data:{action:'advanceToEnd'}})).json();
 expect(ended.eligibility.reason).toBe(1);
 const endedSignal=await request.post('/api/dev/anvil',{data:{action:'sendSignal'}});
 expect(endedSignal.status()).toBe(400);
 expect((await endedSignal.json()).error).toContain('EPOCH ENDED');
 const nextResponse=await request.post('/api/dev/anvil',{data:{action:'startNextEpoch'}});
 expect(nextResponse.ok()).toBeTruthy();
 const next=await nextResponse.json();
 expect(Number(next.epoch.id)).toBe(Number(initial.epoch.id)+1);
 expect(next.epoch.endTime-next.epoch.startTime).toBe(604800);
 expect(next.epoch.totalSignals).toBe(0);
 expect(next.epoch.uniqueParticipants).toBe(0);
});
